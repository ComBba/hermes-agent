from __future__ import annotations

from collections.abc import Sequence
from typing import Protocol


class ExecutionView(Protocol):
    @property
    def profile_id(self) -> str: ...
    @property
    def session_id(self) -> str: ...
    @property
    def admission_id(self) -> str: ...
    @property
    def admission_generation(self) -> int: ...
    @property
    def authority_epoch(self) -> int: ...
    @property
    def principal_id(self) -> str: ...
    @property
    def request_id(self) -> str: ...


class AttachmentView(Protocol):
    @property
    def attachment_id(self) -> str: ...
    @property
    def origin(self) -> str: ...
    @property
    def source_message_id(self) -> str: ...
    @property
    def mime(self) -> str: ...
    @property
    def sha256(self) -> str: ...
    @property
    def size(self) -> int: ...
    @property
    def local_path(self) -> str: ...


class IngressView(ExecutionView, Protocol):
    @property
    def schema_version(self) -> int: ...
    @property
    def caption_present(self) -> bool: ...
    @property
    def current_images(self) -> Sequence[AttachmentView]: ...
    @property
    def platform(self) -> str: ...
    @property
    def actor_id(self) -> str: ...
    @property
    def message_id(self) -> str: ...
    @property
    def event_timestamp(self) -> str: ...
    @property
    def runtime_home(self) -> str: ...
    @property
    def transport_home(self) -> str: ...
    @property
    def transport_profile(self) -> str | None: ...
    @property
    def connector(self) -> str: ...
    @property
    def binding_sha256(self) -> str: ...
    @property
    def reply_to_message_id(self) -> str | None: ...
